const INDEX = new Map<string, ThesaurusEntry>();
for (const e of WORDS) INDEX.set(e.word, e);

/** Normalize a lookup word (lowercase; strip a trailing plural "s"). */
function normalize(word: string): string {
  const w = word.trim().toLowerCase();
  if (INDEX.has(w)) return w;
  if (w.endsWith('s') && INDEX.has(w.slice(0, -1))) return w.slice(0, -1);
  return w;
}

/** Look up synonyms/antonyms; undefined when the word is not in the list. */
export function lookupThesaurus(word: string): ThesaurusEntry | undefined {
  return INDEX.get(normalize(word));
}

/** Number of headwords in the bundled list. */
export function thesaurusSize(): number {
  return WORDS.length;
}

/** All headwords, for search-as-you-type. */
export function thesaurusHeadwords(): string[] {
  return WORDS.map((w) => w.word);
}
