/**
 * Versioned trigger specs (design-docs/automation-lane.md §3 and §5).
 *
 * Triggers live in the service metadata store (MetadataStore), not in the
 * engine, not in the workbook file, not in client component state — the
 * same rule that governs chart and pivot specs. This module is pure and
 * browser-safe: serialization, migration and validation only. Execution
 * lives in runtime.ts (Node-only: it needs the vm/child_process sandbox).
 */

import { MetadataStore, type Persistence } from '../metadataStore.js';
import type { DeclaredPermission } from './api.js';
import type { RangeRef } from '@icecream-sheets/engine';

/** Version of the trigger spec format. Bump on any breaking change. */
export const TRIGGER_SPEC_VERSION = 1;

/** Events a trigger can fire on (automation-lane.md §3). */
export type TriggerEvent =
  | 'onOpen'
  | 'onEdit'
  | 'onSelectionChange'
  | 'onInterval'
  | 'onAtTime';

export type TriggerLanguage = 'javascript' | 'python';

export interface TriggerSpec {
  version: number;
  /** Stable id (uuid-ish; generated by createTriggerSpec when omitted). */
  id: string;
  /** Human-readable name; also used as the automation principal suffix. */
  name: string;
  event: TriggerEvent;
  enabled: boolean;
  /** Optional workbook scope; omitted means "any workbook this host serves". */
  workbookId?: string;
  /** Optional sheet scope for onEdit / onSelectionChange. */
  sheet?: string;
  /** Optional range scope for onEdit / onSelectionChange. */
  range?: RangeRef;
  /** For onInterval: fire every N milliseconds (minimum 1000). */
  intervalMs?: number;
  /** For onAtTime: one-shot ISO-8601 timestamp. */
  atTimeIso?: string;
  /** Last fire time (ISO-8601), maintained by the runtime. */
  lastFiredAt?: string;
  language: TriggerLanguage;
  /** Script source: JS gets a live `api` bridge; Python collects actions. */
  script: string;
  /** Permissions the script declares; the user grants them once. */
  permissions: DeclaredPermission[];
  createdAt: string;
  updatedAt: string;
}

export interface TriggerSpecInit {
  name: string;
  event: TriggerEvent;
  language?: TriggerLanguage;
  script?: string;
  enabled?: boolean;
  workbookId?: string;
  sheet?: string;
  range?: RangeRef;
  intervalMs?: number;
  atTimeIso?: string;
  permissions?: DeclaredPermission[];
}

let triggerSeq = 0;

/** Build a new spec with ids, timestamps and defaults filled in. */
export function createTriggerSpec(init: TriggerSpecInit): TriggerSpec {
  const now = new Date().toISOString();
  const spec: TriggerSpec = {
    version: TRIGGER_SPEC_VERSION,
    id: `trigger-${Date.now().toString(36)}-${(triggerSeq++).toString(36)}`,
    name: init.name,
    event: init.event,
    enabled: init.enabled ?? true,
    language: init.language ?? 'javascript',
    script: init.script ?? '',
    permissions: init.permissions ?? [],
    createdAt: now,
    updatedAt: now,
  };
  if (init.workbookId !== undefined) spec.workbookId = init.workbookId;
  if (init.sheet !== undefined) spec.sheet = init.sheet;
  if (init.range !== undefined) spec.range = { ...init.range };
  if (init.intervalMs !== undefined) spec.intervalMs = init.intervalMs;
  if (init.atTimeIso !== undefined) spec.atTimeIso = init.atTimeIso;
  const problems = validateTriggerSpec(spec);
  if (problems.length > 0) {
    throw new Error(`createTriggerSpec: ${problems.join('; ')}`);
  }
  return spec;
}

/**
 * Validate a spec. Returns a list of human-readable problems (empty when
 * valid). Used by createTriggerSpec, the runtime, and UI forms.
 */
export function validateTriggerSpec(spec: TriggerSpec): string[] {
  const problems: string[] = [];
  if (typeof spec.name !== 'string' || spec.name.trim().length === 0) {
    problems.push('name must be a non-empty string');
  }
  const events: TriggerEvent[] = ['onOpen', 'onEdit', 'onSelectionChange', 'onInterval', 'onAtTime'];
  if (!events.includes(spec.event)) problems.push(`event must be one of ${events.join(', ')}`);
  if (spec.language !== 'javascript' && spec.language !== 'python') {
    problems.push("language must be 'javascript' or 'python'");
  }
  if (typeof spec.script !== 'string' || spec.script.trim().length === 0) {
    problems.push('script must be a non-empty string');
  }
  if (spec.event === 'onInterval') {
    if (!Number.isFinite(spec.intervalMs) || (spec.intervalMs as number) < 1000) {
      problems.push('onInterval triggers need intervalMs >= 1000');
    }
  }
  if (spec.event === 'onAtTime') {
    if (typeof spec.atTimeIso !== 'string' || Number.isNaN(Date.parse(spec.atTimeIso))) {
      problems.push('onAtTime triggers need a valid ISO-8601 atTimeIso');
    }
  }
  if (!Array.isArray(spec.permissions)) {
    problems.push('permissions must be an array');
  } else {
    for (const p of spec.permissions) {
      if (typeof p?.action !== 'string' || typeof p?.target !== 'string') {
        problems.push('each permission needs string action and target');
        break;
      }
    }
  }
  if (spec.range !== undefined) {
    const r = spec.range;
    const ok =
      typeof r.sheet === 'string' &&
      Number.isInteger(r.startRow) &&
      Number.isInteger(r.startCol) &&
      Number.isInteger(r.endRow) &&
      Number.isInteger(r.endCol) &&
      r.endRow >= r.startRow &&
      r.endCol >= r.startCol;
    if (!ok) problems.push('range must be a valid RangeRef');
  }
  return problems;
}

// ---------------------------------------------------------------------------
// Serialization / migration (metadata-store pattern)
// ---------------------------------------------------------------------------

export interface StoredTriggers {
  version: number;
  triggers: TriggerSpec[];
}

/** Serialize trigger specs for the metadata store. */
export function serializeTriggers(triggers: TriggerSpec[]): string {
  const stored: StoredTriggers = { version: TRIGGER_SPEC_VERSION, triggers };
  return JSON.stringify(stored);
}

/**
 * Deserialize trigger specs, migrating older versions forward.
 * Returns an empty list (not an exception) for corrupt payloads,
 * matching the chart/pivot store convention.
 */
export function deserializeTriggers(json: string): TriggerSpec[] {
  let parsed: unknown;
  try {
    parsed = JSON.parse(json);
  } catch {
    return [];
  }
  if (typeof parsed !== 'object' || parsed === null) return [];
  const stored = parsed as Partial<StoredTriggers>;
  if (!Array.isArray(stored.triggers)) return [];
  const out: TriggerSpec[] = [];
  for (const t of stored.triggers) {
    if (typeof t !== 'object' || t === null) continue;
    const migrated = migrateTrigger(t as Partial<TriggerSpec>);
    if (validateTriggerSpec(migrated).length === 0) out.push(migrated);
  }
  return out;
}

/** Migrate a single trigger spec to the current version, filling defaults. */
export function migrateTrigger(spec: Partial<TriggerSpec>): TriggerSpec {
  const now = new Date().toISOString();
  const num = (x: unknown): number | undefined =>
    typeof x === 'number' && Number.isFinite(x) ? x : undefined;
  const str = (x: unknown): string | undefined => (typeof x === 'string' ? x : undefined);
  return {
    version: TRIGGER_SPEC_VERSION,
    id: str(spec.id) ?? `trigger-migrated-${Date.now().toString(36)}`,
    name: str(spec.name) ?? 'Migrated trigger',
    event: isEvent(spec.event) ? spec.event : 'onEdit',
    enabled: spec.enabled !== false,
    language: spec.language === 'python' ? 'python' : 'javascript',
    script: str(spec.script) ?? '',
    permissions: Array.isArray(spec.permissions)
      ? spec.permissions.filter(
          (p): p is DeclaredPermission =>
            typeof p === 'object' &&
            p !== null &&
            typeof (p as DeclaredPermission).action === 'string' &&
            typeof (p as DeclaredPermission).target === 'string',
        )
      : [],
    createdAt: str(spec.createdAt) ?? now,
    updatedAt: now,
    ...(str(spec.workbookId) !== undefined ? { workbookId: str(spec.workbookId) } : {}),
    ...(str(spec.sheet) !== undefined ? { sheet: str(spec.sheet) } : {}),
    ...(spec.range !== undefined ? { range: spec.range } : {}),
    ...(num(spec.intervalMs) !== undefined ? { intervalMs: num(spec.intervalMs) } : {}),
    ...(str(spec.atTimeIso) !== undefined ? { atTimeIso: str(spec.atTimeIso) } : {}),
    ...(str(spec.lastFiredAt) !== undefined ? { lastFiredAt: str(spec.lastFiredAt) } : {}),
  };
}

function isEvent(v: unknown): v is TriggerEvent {
  return (
    v === 'onOpen' || v === 'onEdit' || v === 'onSelectionChange' || v === 'onInterval' || v === 'onAtTime'
  );
}

/** Storage key for trigger specs in the metadata store. */
export const TRIGGER_STORE_KEY = 'icecream-sheets.triggers.v1';

/** Create a trigger-spec metadata store bound to a persistence adapter. */
export function createTriggerStore(persistence: Persistence): MetadataStore<TriggerSpec> {
  return new MetadataStore<TriggerSpec>(
    TRIGGER_STORE_KEY,
    persistence,
    serializeTriggers,
    deserializeTriggers,
  );
}
